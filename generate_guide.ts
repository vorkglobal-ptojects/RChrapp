import PDFDocument from 'pdfkit';
import fs from 'fs';
import path from 'path';

function generateGuide() {
  const doc = new PDFDocument({ margin: 50 });
  const outputPath = path.join(process.cwd(), 'Attendance_Support_Ticket_Guide.pdf');
  
  doc.pipe(fs.createWriteStream(outputPath));

  // Cover Page
  doc.fontSize(24).font('Helvetica-Bold').text('HR Pulse', { align: 'center' });
  doc.moveDown();
  doc.fontSize(18).text('Attendance Support Ticket System Guide', { align: 'center' });
  doc.moveDown(2);
  doc.fontSize(12).font('Helvetica').text('This guide explains how to use the new Attendance Support Ticket system to correct missing check-in or check-out times.', { align: 'center' });
  
  doc.moveDown(4);

  // For Employees Section
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#f97316').text('For Employees');
  doc.fillColor('#000000');
  doc.moveDown();
  
  doc.fontSize(12).font('Helvetica').text('If you forget to Check-In or Check-Out during your shift, you can now submit a request to get it fixed:');
  doc.moveDown();
  
  doc.font('Helvetica-Bold').text('Step 1: Navigate to the Requests Tab');
  doc.font('Helvetica').text('Go to the Attendance page from the sidebar. Click on the "Requests" tab located next to "Logs".');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Step 2: Create a New Request');
  doc.font('Helvetica').text('Click the black "New Request" button. A modal will appear.');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Step 3: Fill out the details');
  doc.font('Helvetica').text('- Select the Date you missed the log.');
  doc.text('- Select the "Missing Action" (Missed Check-In, Missed Check-Out, or Missed Both).');
  doc.text('- Enter the correct time you intended to check in or out.');
  doc.text('- Provide a short reason explaining what happened.');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Step 4: Submit');
  doc.font('Helvetica').text('Click "Submit Request". Your manager or HR will review and approve it. Once approved, your attendance log will be automatically updated.');

  doc.moveDown(3);

  // For Supervisors/HR Section
  doc.fontSize(16).font('Helvetica-Bold').fillColor('#f97316').text('For Supervisors and HR');
  doc.fillColor('#000000');
  doc.moveDown();

  doc.fontSize(12).font('Helvetica').text('You can review and manage employee attendance requests from the dashboard:');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Reviewing Tickets');
  doc.font('Helvetica').text('Go to the Attendance page, then select the "Requests" tab. You will see a list of all tickets across all employees.');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Approving or Rejecting');
  doc.font('Helvetica').text('For any "Pending" ticket, you will see "Approve" and "Reject" buttons on the right side. When you click Approve, the system will automatically update the employee\'s main attendance log with the requested times.');
  doc.moveDown();

  doc.font('Helvetica-Bold').text('Note:');
  doc.font('Helvetica').text('If an attendance record already exists for that day, the system will seamlessly merge the new check-in/out times into it.');

  doc.moveDown(4);
  doc.fontSize(10).fillColor('#6b7280').text('Generated by HR Pulse Automated Assistant', { align: 'center' });

  doc.end();
  
  console.log(`PDF generated successfully at ${outputPath}`);
}

generateGuide();
